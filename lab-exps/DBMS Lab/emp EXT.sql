CREATE OR REPLACE PROCEDURE show_emp (id NUMBER)
IS
    e EMP%ROWTYPE;
BEGIN
    SELECT * INTO e
    FROM EMP
    WHERE EMPNO = id;

    DBMS_OUTPUT.PUT_LINE('EMPNO: ' || e.EMPNO);
    DBMS_OUTPUT.PUT_LINE('ENAME: ' || e.ENAME);
    DBMS_OUTPUT.PUT_LINE('JOB: ' || e.JOB);
    DBMS_OUTPUT.PUT_LINE('SAL: ' || e.SAL);
    DBMS_OUTPUT.PUT_LINE('DEPTNO: ' || e.DEPTNO);
END;
/

BEGIN
