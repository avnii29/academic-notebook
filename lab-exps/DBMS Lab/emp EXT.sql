CREATE OR REPLACE PROCEDURE get_annual_sal (
    id IN NUMBER,
    ann_sal OUT NUMBER
)
IS
BEGIN
    SELECT SAL * 12 INTO ann_sal
    FROM EMP
    WHERE EMPNO = id;
END;
/


