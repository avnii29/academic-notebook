CREATE OR REPLACE PACKAGE HR_PACKAGE AS
       PROCEDURE HIRE(ID NUMBER , NAME VARCHAR2 , JOB VARCHAR2 , SAL NUMBER , DEPT NUMBER);

       PROCEDURE FIRE(ID NUMBER);

END HR_PACKAGE;

CREATE OR REPLACE PACKAGE BODY HR_PACKAGE AS
            PROCEDURE HIRE (ID NUMBER , NAME VARCHAR2 , JOB VARCHAR2 , SAL NUMBER , DEPT NUMBER)
            IS 
            BEGIN
                INSERT INTO EMP(EMPNO , ENAME , JOB , SAL , DEPTNO) VALUES (ID , NAME , JOB , SAL , DEPT);

                DBMS_OUTPUT.PUT_LINE('RECORD INSERTED');
            END HIRE;

            PROCEDURE FIRE(ID NUMBER)
            IS
            BEGIN
                DELETE FROM EMP WHERE EMPNO = ID;

                DBMS_OUTPUT.PUT_LINE('RECORD DELETED');
            END FIRE;
END HR_PACKAGE;

BEGIN
   HR_PACKAGE.HIRE(33, 'KAVYA', 'ANALYST', 4000, 10);
   HR_PACKAGE.FIRE(33);
END;
/

