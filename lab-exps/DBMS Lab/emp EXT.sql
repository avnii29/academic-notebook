CREATE OR REPLACE FUNCTION get_dname (id NUMBER)
RETURN VARCHAR2
IS
    v_dname VARCHAR2(50);
BEGIN
    SELECT DNAME INTO v_dname
    FROM DEPT
    WHERE DEPTNO = id;

    RETURN v_dname;
END;
/


