CREATE OR REPLACE PROCEDURE SHOW_SAILORS (ID NUMBER)
IS
   S SAILORS %ROWTYPE;
BEGIN
     SELECT * INTO S 
     FROM SAILORS WHERE SID = ID;
     DBMS_OUTPUT.PUT_LINE('SID:' ||  S.SID);
     DBMS_OUTPUT.PUT_LINE('SNAME:'|| S.SNAME);
     DBMS_OUTPUT.PUT_LINE('RATING:' || S.RATING);
     DBMS_OUTPUT.PUT_LINE('AGE:' || S.AGE);
END;
/

