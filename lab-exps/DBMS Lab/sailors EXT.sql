CREATE OR REPLACE TRIGGER PREV_DUPLI
BEFORE INSERT ON SAILORS
FOR EACH ROW
DECLARE
     V_COUNT NUMBER;
BEGIN
     SELECT COUNT(*) INTO V_COUNT
     FROM SAILORS WHERE SID = :NEW.SID;

     IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(-20001 , 'DUPLICATE SID NOT ALLOWED');
     END IF;
END;
/

