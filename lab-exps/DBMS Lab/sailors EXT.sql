CREATE OR REPLACE FUNCTION GET_AGE(ID NUMBER)
RETURN NUMBER
IS
   S_AGE NUMBER;
BEGIN
   SELECT AGE INTO S_AGE
   FROM SAILORS 
   WHERE SID = ID;

   RETURN S_AGE;
END;
/

